// Version the complete local module graph, including worker entry points.
// GitHub Pages serves main directly, so these changes are checked in with a release.
import {readFile,writeFile,readdir} from 'node:fs/promises';
const {version}=JSON.parse(await readFile('package.json','utf8'));
if(!/^\d+\.\d+\.\d+$/.test(version))throw Error('Expected a semantic release version.');
for(const entry of await readdir('src',{withFileTypes:true})){
 if(!entry.isFile()||!entry.name.endsWith('.js')||entry.name==='release-version.js')continue;
 const path='src/'+entry.name,original=await readFile(path,'utf8');
 let text=original.replace(/((?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s*|\bnew URL\s*\(\s*)['"])(\.[^'"\n?]+\.js)(?:\?v=[^'"\n]*)?(['"])/g,(_,prefix,url,end)=>prefix+url+'?v='+version+end);
 text=text.replace(/(fetch\(['"])(\.\/data\/[^'"?]+\.json)(?:\?v=[^'"]*)?(['"])/g,(_,prefix,url,end)=>prefix+url+'?v='+version+end);
 if(text!==original)await writeFile(path,text);
}
const path='index.html',original=await readFile(path,'utf8');
const html=original.replace(/((?:src|href)=["'])(\.\/src\/[^"'?]+\.(?:js|css))(?:\?v=[^"']*)?(["'])/g,(_,prefix,url,end)=>prefix+url+'?v='+version+end);
if(html!==original)await writeFile(path,html);
const release=`// Generated by tools/stamp-release.mjs.\nexport const RELEASE_VERSION=${JSON.stringify(version)};\n`;
await writeFile('src/release-version.js',release);
console.log('Release asset URLs: '+version);
